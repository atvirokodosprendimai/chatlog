# gen-formula.sh VERSION SHA256SUMS > Formula/chatlog.rb
# Writes the Homebrew formula for one release, from the release's SHA256SUMS (scripts/release-build.sh writes it; CI
# uploads it beside the tarballs). The formula lives in this repository, which is its own tap; the same inputs give
# the same formula, so it can be rebuilt from any release.
set -eu
version=${1:?usage: gen-formula.sh VERSION SHA256SUMS}
version=${version#v}
sums=${2:?usage: gen-formula.sh VERSION SHA256SUMS}
base="https://github.com/atvirokodosprendimai/chatlog/releases/download/v${version}"

sha() {
	s=$(awk -v f="chatlog_${version}_$1.tar.gz" '$2 == f { print $1 }' "$sums")
	if [ -z "$s" ]; then
		echo "gen-formula.sh: no chatlog_${version}_$1.tar.gz in $sums" >&2
		exit 1
	fi
	printf '%s' "$s"
}

# computed before the heredoc: an exit inside $(...) there would end only that subshell and leave sha256 ""
sha_darwin_arm64=$(sha darwin_arm64)
sha_darwin_amd64=$(sha darwin_amd64)
sha_linux_arm64=$(sha linux_arm64)
sha_linux_amd64=$(sha linux_amd64)

cat <<RUBY
# SPDX-License-Identifier: AGPL-3.0-only
# Generated by packaging/homebrew/gen-formula.sh from the v${version} release; do not edit by hand.
class Chatlog < Formula
  desc "Searchable record of your Claude Code sessions, recalled through MCP"
  homepage "https://github.com/atvirokodosprendimai/chatlog"
  version "${version}"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "${base}/chatlog_${version}_darwin_arm64.tar.gz"
      sha256 "${sha_darwin_arm64}"
    end
    on_intel do
      url "${base}/chatlog_${version}_darwin_amd64.tar.gz"
      sha256 "${sha_darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/chatlog_${version}_linux_arm64.tar.gz"
      sha256 "${sha_linux_arm64}"
    end
    on_intel do
      url "${base}/chatlog_${version}_linux_amd64.tar.gz"
      sha256 "${sha_linux_amd64}"
    end
  end

  def install
    bin.install "chatlog"
    doc.install "README.md", "INSTALL.md", "docs"
  end

  def caveats
    <<~EOS
      To wire chatlog into Claude Code (hooks, MCP server, skill), run:
        chatlog install --bin #{HOMEBREW_PREFIX}/bin/chatlog
      then check it with:
        chatlog doctor
      and restart Claude Code. chatlog install --uninstall takes it out again.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/chatlog --version")
    assert_match "FIRST CLASS TOOL", shell_output("#{bin}/chatlog instructions --core")
  end
end
RUBY
